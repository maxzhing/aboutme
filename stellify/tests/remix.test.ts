import { describe, expect, it } from 'vitest';
import { QUESTIONS } from '@/data/questions';
import { MATH_FAMILIES } from '@/lib/remix/math';
import { RW_FAMILIES, RW_MODES } from '@/lib/remix/rw';
import { buildCorpus, generate, MAX_ATTEMPTS, modesFor, remixable, smartPick } from '@/lib/remix/engine';
import { parseAi } from '@/lib/remix/ai';
import { grams, validate } from '@/lib/remix/validate';
import { rng } from '@/lib/util';
import type { Candidate, RemixLevel, RemixMode } from '@/lib/remix/types';
import { STUDIES } from '@/lib/remix/rwBank';

const MODES: RemixMode[] = ['number', 'context', 'representation', 'reverse', 'reasoning', 'challenge'];
const LEVELS: RemixLevel[] = [1, 3, 5];
const GENRES = ['science', 'literature', 'history-social', 'humanities'] as const;
const failed = (c: Candidate) => validate(c).checks.filter((k) => !k.pass).map((k) => `${k.name} ${k.detail ?? ''}`);
const sample = (skill: string) => QUESTIONS.find((q) => q.skill === skill)!;

describe('Remix: math generators', () => {
  for (const [skill, f] of Object.entries(MATH_FAMILIES)) {
    it(`${skill} (${f!.name}): every generated question passes the independent validator`, () => {
      let made = 0;
      for (const mode of MODES) for (const level of LEVELS) for (let s = 0; s < 12; s++) {
        const c = f!.family(rng(`t-${skill}-${mode}-${level}-${s}`), level, mode, skill as never);
        if (!c) continue; // degenerate values are rejected by the family itself and regenerated by the engine
        made++;
        expect(failed(c), `${mode} L${level} #${s}: ${c.stem}`).toEqual([]);
        expect(c.skill).toBe(skill);
        expect(c.hints).toHaveLength(3);
      }
      expect(made).toBeGreaterThan(MODES.length * LEVELS.length * 6);
    });
  }
});

describe('Remix: Reading & Writing generators', () => {
  for (const [skill, f] of Object.entries(RW_FAMILIES)) {
    it(`${skill} (${f!.name}): every offered mode yields valid, College Board-shaped questions`, () => {
      const modes = MODES.filter((m) => RW_MODES[skill as never]?.[m]);
      expect(modes.length).toBeGreaterThanOrEqual(4);
      for (const mode of modes) for (const level of LEVELS) for (let s = 0; s < 8; s++) {
        const c = f!.family(rng(`t-${skill}-${mode}-${level}-${s}`), level, mode, { genre: GENRES[s % 4] });
        expect(c, `${mode} L${level} #${s}`).not.toBeNull();
        expect(failed(c!), `${mode} L${level} #${s}: ${c!.stem}`).toEqual([]);
      }
    });
  }
  it('covers all four Reading & Writing domains (11 skills)', () => {
    expect(Object.keys(RW_FAMILIES).sort()).toEqual(['bnd', 'cid', 'coeq', 'coet', 'ctc', 'fss', 'inf', 'syn', 'tra', 'tsp', 'wic']);
  });
  it('context mode moves to a different subject area', () => {
    for (let s = 0; s < 20; s++) {
      const c = RW_FAMILIES.cid!.family(rng(`ctx-${s}`), 3, 'context', { genre: 'science' })!;
      expect(STUDIES.find((x) => c.passage?.includes(x.s[1]))!.genre).not.toBe('science');
    }
  });
  it('no generated passage copies an 8-word run from the question bank', () => {
    const corpus = buildCorpus(QUESTIONS);
    for (const [skill, f] of Object.entries(RW_FAMILIES)) for (const mode of MODES) {
      if (!RW_MODES[skill as never]?.[mode]) continue;
      for (let s = 0; s < 6; s++) {
        const c = f!.family(rng(`orig-${skill}-${mode}-${s}`), 3, mode, {})!;
        const mine = grams(`${c.passage ?? ''} ${(c.notes ?? []).join(' ')}`);
        expect([...mine].filter((g) => corpus.has(g)), `${skill}/${mode}`).toEqual([]);
      }
    }
  });
});

describe('Remix: the validator rejects corrupted questions (mutation tests)', () => {
  const math = MATH_FAMILIES.lin1!.family(rng('mut-1'), 3, 'number', 'lin1')!;
  it('a valid math question passes', () => expect(validate(math).ok).toBe(true));
  it('a wrong answer key is caught', () => {
    const bad = { ...math, answer: ((math.answer as number) + 1) % 4 };
    expect(validate(bad).checks.find((k) => k.name === 'answer key matches the solved value')!.pass).toBe(false);
  });
  it('a second correct choice is caught', () => {
    const key = math.choices![math.answer as number];
    const other = ((math.answer as number) + 1) % 4;
    const choices = math.choices!.map((c, i) => (i === other ? `${key} ` : c));
    const spec = { ...math.spec, choiceExprs: undefined } as Candidate['spec'];
    expect(validate({ ...math, choices, spec }).ok).toBe(false);
  });
  it('a changed equation (spec no longer matches the key) is caught', () => {
    if (math.spec.t !== 'solve') return;
    const spec = { ...math.spec, eq: math.spec.eq.replace(/=(.*)$/, '=($1)+1') };
    expect(validate({ ...math, spec }).ok).toBe(false);
  });
  it('an unsolvable problem is caught', () => {
    expect(validate({ ...math, spec: { t: 'solve', eq: 'x*x+1=0' } }).checks.find((k) => k.name === 'problem is well posed')!.pass).toBe(false);
  });
  it('a hint that gives away the answer is caught', () => {
    const key = math.choices![math.answer as number];
    expect(validate({ ...math, hints: [math.hints[0], `The answer is ${key}.`, math.hints[2]] }).ok).toBe(false);
  });
  it('an unfilled template slot is caught', () => {
    expect(validate({ ...math, stem: 'A {service_name} charges a fee. What is x?' }).ok).toBe(false);
  });
  const rw = RW_FAMILIES.cid!.family(rng('mut-2'), 3, 'number', {})!;
  it('a valid R&W question passes', () => expect(validate(rw).ok).toBe(true));
  it('R&W: a wrong key is caught', () => {
    expect(validate({ ...rw, answer: ((rw.answer as number) + 1) % 4 }).ok).toBe(false);
  });
  it('R&W: two defensible answers are caught', () => {
    if (rw.spec.t !== 'tags') return;
    const tags = rw.spec.tags.map((t, i) => (i === ((rw.answer as number) + 1) % 4 ? rw.spec.t === 'tags' ? rw.spec.want : t : t));
    expect(validate({ ...rw, spec: { ...rw.spec, tags } }).ok).toBe(false);
  });
  it('R&W: a passage outside the 25–150 word rule is caught', () => {
    expect(validate({ ...rw, passage: 'Too short to be a passage.' }).ok).toBe(false);
  });
  it('R&W: a non-official stem is caught', () => {
    expect(validate({ ...rw, stem: 'What is this passage mostly about?' }).ok).toBe(false);
  });
  it('data: a statement that misreads the table cannot be the key', () => {
    const d = RW_FAMILIES.coeq!.family(rng('mut-3'), 3, 'number', {})!;
    expect(validate(d).ok).toBe(true);
    if (d.spec.t !== 'data') return;
    const stmts = d.spec.stmts.map((s, i) => (i === d.answer ? { ...s, claims: s.claims.map((c) => ({ ...c, dir: c.dir === 'up' ? 'down' as const : 'up' as const })) } : s));
    expect(validate({ ...d, spec: { ...d.spec, stmts } }).ok).toBe(false);
  });
  it('grammar: a second acceptable form is caught', () => {
    const g = RW_FAMILIES.bnd!.family(rng('mut-4'), 3, 'number', {})!;
    if (g.spec.t !== 'grammar') return;
    expect(validate({ ...g, spec: { ...g.spec, valid: g.spec.options.slice(0, 2) } }).ok).toBe(false);
  });
  it('synthesis: a sentence using information outside the notes is caught', () => {
    const y = RW_FAMILIES.syn!.family(rng('mut-5'), 3, 'number', {})!;
    if (y.spec.t !== 'facts') return;
    expect(validate({ ...y, spec: { ...y.spec, choiceFacts: y.spec.choiceFacts.map((f, i) => (i === 0 ? [...f, 'zz9'] : f)) } }).ok).toBe(false);
  });
});

describe('Remix engine', () => {
  const base = { originId: 'o', chainId: 'c1', seed: 'seed', now: 1_800_000_000_000 };
  it('generates a validated, labelled question for every supported skill in the bank', () => {
    for (const skill of [...Object.keys(MATH_FAMILIES), ...Object.keys(RW_FAMILIES)]) {
      const q = sample(skill);
      if (!q) continue;
      const r = generate({ ...base, parent: q, originId: q.id, mode: 'number', level: 3 });
      expect(r.ok, `${skill}: ${!r.ok ? r.rejected.join(' | ') : ''}`).toBe(true);
      if (!r.ok) continue;
      expect(r.question.id.startsWith('gx-')).toBe(true);
      expect(r.question.remix.status).toBe('auto-validated');
      expect(r.question.remix.validation.ok).toBe(true);
      expect(r.question.source).toMatch(/not an official College Board question/);
      expect(r.question.skill).toBe(skill);
    }
  });
  it('is deterministic for a seed and never repeats an earlier variation', () => {
    const q = sample('lin1');
    const a = generate({ ...base, parent: q, mode: 'number', level: 3 });
    const b = generate({ ...base, parent: q, mode: 'number', level: 3 });
    expect(a.ok && b.ok && a.question.id === b.question.id).toBe(true);
    if (!a.ok) return;
    const sig = `${a.question.stem}|${(a.question.choices ?? []).join('|')}|${a.question.passage ?? ''}`;
    const c = generate({ ...base, parent: q, mode: 'number', level: 3, previous: [sig] });
    expect(c.ok && c.question.id).not.toBe(a.question.id);
  });
  it('refuses an unavailable transformation with an honest note', () => {
    const r = generate({ ...base, parent: sample('tra'), mode: 'reverse', level: 3 });
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.reason).toMatch(/not offered rather than faked/);
    expect(modesFor(sample('tra')).filter((m) => m.ok).map((m) => m.mode)).not.toContain('reverse');
  });
  it('reports clearly when every retry fails', () => {
    // a corpus containing every passage in the R&W content bank forces the originality check to fail
    const all = new Set<string>();
    for (const [skill, f] of Object.entries(RW_FAMILIES)) for (const m of MODES) for (let s = 0; s < 60; s++) {
      if (!RW_MODES[skill as never]?.[m]) continue;
      const c = f!.family(rng(`all-${skill}-${m}-${s}`), (1 + (s % 5)) as RemixLevel, m, { genre: GENRES[s % 4] });
      if (c) for (const g of grams(`${c.passage ?? ''} ${(c.notes ?? []).join(' ')}`)) all.add(g);
    }
    const r = generate({ ...base, parent: sample('cid'), mode: 'number', level: 3, corpus: all });
    expect(r.ok).toBe(false);
    if (!r.ok) { expect(r.reason).toMatch(String(MAX_ATTEMPTS)); expect(r.rejected.length).toBe(MAX_ATTEMPTS); expect(r.rejected[0]).toMatch(/original wording/); }
  });
  it('falls back to local generation when the AI candidate is malformed', () => {
    const q = sample('lin1');
    expect(parseAi({ stem: 'x' }, q, 'number', 3)).toBeNull();
    expect(parseAi('not json', q, 'number', 3)).toBeNull();
    const r = generate({ ...base, parent: q, mode: 'number', level: 3, aiCandidate: null });
    expect(r.ok).toBe(true);
    if (r.ok) { expect(r.question.remix.method).toBe('local'); expect(r.question.remix.rejected[0]).toMatch(/^ai:/); }
  });
  it('validates an AI candidate exactly like a local one, and rejects a wrong AI key', () => {
    const q = sample('lin1');
    const good = { stem: 'If $3x + 5 = 20$, what is the value of $x$?', choices: ['$3$', '$5$', '$15$', '$25$'], answer: 1, steps: ['Subtract 5: $3x = 15$.', 'Divide by 3: $x = 5$.'], why: ['Divides before subtracting.', 'Correct.', 'Stops at 3x.', 'Adds 5 instead of subtracting.'], concept: 'Undo operations in reverse order.', strategy: 'Subtract, then divide.', trap: 'Stopping at 3x = 15.', hints: ['What is being done to x?', 'Undo the + 5 first.', 'Then undo the multiplication.'], differs: 'New numbers.', specType: 'solve', equation: '3*x+5=20', ask: 'x' };
    const ok = generate({ ...base, parent: q, mode: 'number', level: 3, aiCandidate: parseAi(good, q, 'number', 3) });
    expect(ok.ok && ok.question.remix.method).toBe('ai');
    const wrong = generate({ ...base, parent: q, mode: 'number', level: 3, aiCandidate: parseAi({ ...good, answer: 2 }, q, 'number', 3) });
    expect(wrong.ok && wrong.question.remix.method).toBe('local');
    const rwq = sample('cid');
    const rwAi = parseAi({ ...good, passage: STUDIES[0].s.join(' '), stem: 'Which choice best states the main idea of the text?', choices: [STUDIES[0].main, STUDIES[0].beyond, STUDIES[0].reversed, STUDIES[0].off[0]], answer: 0, specType: 'tags', tags: ['main', 'broad', 'reversed', 'off'], want: 'main' }, rwq, 'number', 3);
    const r2 = generate({ ...base, parent: rwq, mode: 'number', level: 3, aiCandidate: rwAi });
    expect(r2.ok && r2.question.remix.status).toBe('needs-review');
  });
  it('refuses questions it cannot remix', () => {
    expect(remixable(undefined).ok).toBe(false);
    expect(remixable({ ...sample('lin1'), skill: 'nope' as never }).ok).toBe(false);
  });
});

describe('Smart Remix', () => {
  const q = sample('lin1'), t = sample('tra');
  it('steps down after a conceptual miss and says why', () => {
    const p = smartPick({ question: q, last: { correct: false }, mistake: 'concept' });
    expect(p.mode).toBe('number'); expect(p.level).toBeLessThan(4); expect(p.reason).toMatch(/gap/);
  });
  it('changes the form after a misreading', () => expect(smartPick({ question: q, last: { correct: false }, mistake: 'misread' }).mode).toBe('representation'));
  it('re-tests a lucky guess at the same level', () => {
    const p = smartPick({ question: q, last: { correct: true, confidence: 'guess' } });
    expect(p.mode).toBe('number'); expect(p.reason).toMatch(/guessing/);
  });
  it('challenges a strong, sure student', () => expect(smartPick({ question: q, last: { correct: true, confidence: 'sure' }, skill: { n: 10, acc: 0.9 } }).mode).toBe('challenge'));
  it('only suggests modes the skill supports', () => {
    for (const last of [{ correct: true, confidence: 'sure' as const }, { correct: false }]) expect(modesFor(t).find((m) => m.mode === smartPick({ question: t, last, mistake: 'misread' }).mode)!.ok).toBe(true);
  });
  it('adapts along a chain', () => {
    expect(smartPick({ question: q, chain: [{ mode: 'number', level: 3, correct: false }] }).level).toBe(2);
    expect(smartPick({ question: q, chain: [{ mode: 'number', level: 3, correct: true }, { mode: 'reverse', level: 3, correct: true }] }).level).toBe(4);
  });
});
