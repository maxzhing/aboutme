type Patch = Partial<RawQuestion> & { id: string };
const solve2 = (a1: number, b1: number, c1: number, a2: number, b2: number, c2: number): [number, number] | null => {
  const det = a1 * b2 - a2 * b1; if (Math.abs(det) < 1e-12) return null;
  return [(c1 * b2 - c2 * b1) / det, (a1 * c2 - a2 * c1) / det];
};
/** classify a1x + b1y = c1, a2x + b2y = c2 */
const kind = (a1: number, b1: number, c1: number, a2: number, b2: number, c2: number) => {
  if (Math.abs(a1 * b2 - a2 * b1) > 1e-12) return 'one';
  return Math.abs(a1 * c2 - a2 * c1) < 1e-12 && Math.abs(b1 * c2 - b2 * c1) < 1e-12 ? 'infinite' : 'none';
};
