export function provenanceLabel(p: Provenance): string {
  switch (p.kind) {
    case 'verified':
      return p.lastVerified ? `Verified ${p.lastVerified}` : 'Verified';
    case 'ai':
      return 'AI guidance';
    case 'user':
      return 'You entered this';
    case 'demo':
      return 'Demo data';
    default:
      return 'Unverified';
  }
}
